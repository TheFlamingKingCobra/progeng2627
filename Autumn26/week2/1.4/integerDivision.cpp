#include <iostream>

int main(){
    std::cout << "Here is an example of integer division without decimal points (compiler interprets numbers as integers): 5/2 = " 
    << 5/2 << std::endl;

    std::cout << "Here is an example of integer division with decimal points (compiler interprets numbers as a floating point number): 5/2 = " 
    << 5/2.0 << std::endl;
}